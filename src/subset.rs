//! Subsets of a finite universe — the **indication tier** `Sub(U)`.
//!
//! The partition lattice is the categorical dual of this one (Ellerman). L-VM computes in
//! `Sub(U × U)` already — `h(π) = |dit(π)|/N²`, `d_⊕ = |dit △ dit|/N²`,
//! [`crate::incidence::destr`]/[`crate::incidence::creat`] are set differences — but only ever
//! as **cardinalities**, never as objects. This module is that missing home: it holds the
//! Boolean operations themselves so nothing else has to re-implement them.
//!
//! **Scope.** The Boolean algebra `(∪, ∩, ¬, △)` only. The *bridges* to the partition tier
//! (`dit`, the coreflection `int`, the cross `K`) are deliberately absent — they are bounded
//! rather than universal, and mixing them in here would blur that line.
//!
//! ## Why `|U| = 1` is the interesting case
//!
//! Boolean algebras are the variety generated by the two-element one, and every Boolean
//! algebra is a subdirect product of copies of it (Stone). So an **identity** between Boolean
//! terms holds in *every* Boolean algebra exactly when it holds in `Sub(U)` for `|U| = 1`.
//! That is why [`all_subsets`] over a one-element universe decides identities outright, while
//! the same enumeration over larger universes is only a cross-check.
//!
//! ⚠ **This is about Boolean algebras, not about subobject lattices in general.** In a
//! non-Boolean topos `Sub(X)` is Heyting and `¬¬A = A` fails, so a verdict from here must not
//! be read as "true in every subobject lattice".

use alloc::vec;
use alloc::vec::Vec;

/// A subset of `{0, ..., n-1}`, stored as one bit per element.
///
/// Two subsets are comparable only over the same universe; operations take that on trust,
/// mirroring the rest of the crate (the boundary that checks is the caller's).
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct SubsetU {
    n: usize,
    words: Vec<u64>,
}

#[inline]
fn words_for(n: usize) -> usize {
    n.div_ceil(64)
}

impl SubsetU {
    /// The empty subset of an `n`-element universe.
    pub fn empty(n: usize) -> Self {
        Self { n, words: vec![0u64; words_for(n)] }
    }

    /// The whole universe.
    pub fn full(n: usize) -> Self {
        let mut s = Self::empty(n);
        for i in 0..n {
            s.insert(i);
        }
        s
    }

    /// Build from element indices; indices `>= n` are ignored.
    pub fn from_indices(n: usize, idx: &[usize]) -> Self {
        let mut s = Self::empty(n);
        for &i in idx {
            if i < n {
                s.insert(i);
            }
        }
        s
    }

    /// Size of the universe, not of the subset (that is [`Self::card`]).
    #[inline]
    pub fn size(&self) -> usize {
        self.n
    }

    #[inline]
    fn insert(&mut self, i: usize) {
        self.words[i / 64] |= 1u64 << (i % 64);
    }

    #[inline]
    pub fn contains(&self, i: usize) -> bool {
        i < self.n && (self.words[i / 64] >> (i % 64)) & 1 == 1
    }

    /// Number of elements in the subset.
    pub fn card(&self) -> usize {
        self.words.iter().map(|w| w.count_ones() as usize).sum()
    }

    pub fn to_indices(&self) -> Vec<usize> {
        (0..self.n).filter(|&i| self.contains(i)).collect()
    }

    fn zip_with(&self, other: &Self, f: impl Fn(u64, u64) -> u64) -> Self {
        let mut out = Self::empty(self.n);
        for (k, w) in out.words.iter_mut().enumerate() {
            *w = f(self.words[k], other.words[k]);
        }
        out.mask_tail();
        out
    }

    /// Clear bits past `n` in the last word, so equality and `card` cannot see padding.
    #[inline]
    fn mask_tail(&mut self) {
        let rem = self.n % 64;
        if rem != 0 {
            if let Some(last) = self.words.last_mut() {
                *last &= (1u64 << rem) - 1;
            }
        }
    }

    pub fn union(&self, other: &Self) -> Self {
        self.zip_with(other, |a, b| a | b)
    }

    pub fn inter(&self, other: &Self) -> Self {
        self.zip_with(other, |a, b| a & b)
    }

    /// Boolean complement. **Unique and total** — the property the partition tier does not
    /// have (`Π(U)` is complemented but not uniquely so, Ore 1942), and the reason
    /// `partition-logic` refuses a unary `Comp` on partitions.
    pub fn neg(&self) -> Self {
        let mut out = Self::empty(self.n);
        for (k, w) in out.words.iter_mut().enumerate() {
            *w = !self.words[k];
        }
        out.mask_tail();
        out
    }

    /// Symmetric difference — addition of the Boolean *ring*. `dit_xor_count` is the
    /// cardinality of exactly this, taken in `Sub(U × U)`.
    pub fn sym_diff(&self, other: &Self) -> Self {
        self.zip_with(other, |a, b| a ^ b)
    }

    /// `self ⊆ other`.
    pub fn subset_of(&self, other: &Self) -> bool {
        self.words.iter().zip(&other.words).all(|(a, b)| a & !b == 0)
    }
}

/// Every subset of `{0, ..., n-1}`, in increasing bitmask order — `2^n` of them.
///
/// At `n = 1` this is the two-element Boolean algebra, which decides identities for *all*
/// Boolean algebras (see the module docs).
pub fn all_subsets(n: usize) -> Vec<SubsetU> {
    let total = 1usize << n;
    (0..total)
        .map(|m| {
            let mut s = SubsetU::empty(n);
            for i in 0..n {
                if (m >> i) & 1 == 1 {
                    s.insert(i);
                }
            }
            s
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_subset_empty_and_full_are_complements() {
        for n in 0..5 {
            assert_eq!(SubsetU::empty(n).neg(), SubsetU::full(n));
            assert_eq!(SubsetU::full(n).neg(), SubsetU::empty(n));
            assert_eq!(SubsetU::full(n).card(), n);
            assert_eq!(SubsetU::empty(n).card(), 0);
        }
    }

    #[test]
    fn test_subset_padding_is_invisible() {
        // n = 3 lives in one 64-bit word; the other 61 bits must never show up.
        let s = SubsetU::from_indices(3, &[0, 1, 2]);
        assert_eq!(s.card(), 3);
        assert_eq!(s.neg().card(), 0);
        assert_eq!(s.neg(), SubsetU::empty(3));
    }

    #[test]
    fn test_subset_from_indices_ignores_out_of_range() {
        assert_eq!(SubsetU::from_indices(3, &[0, 9]).to_indices(), vec![0]);
    }

    #[test]
    fn test_subset_all_subsets_counts_two_to_the_n() {
        for n in 0..7 {
            let all = all_subsets(n);
            assert_eq!(all.len(), 1usize << n);
            let mut seen = all.clone();
            seen.sort();
            seen.dedup();
            assert_eq!(seen.len(), all.len(), "all_subsets must be distinct");
        }
    }

    #[test]
    fn test_subset_boolean_axioms_hold_exhaustively() {
        for n in 0..4 {
            for a in &all_subsets(n) {
                for b in &all_subsets(n) {
                    // De Morgan
                    assert_eq!(a.union(b).neg(), a.neg().inter(&b.neg()));
                    assert_eq!(a.inter(b).neg(), a.neg().union(&b.neg()));
                    // complement laws
                    assert_eq!(a.inter(&a.neg()), SubsetU::empty(n));
                    assert_eq!(a.union(&a.neg()), SubsetU::full(n));
                    // double negation
                    assert_eq!(a.neg().neg(), *a);
                    // symmetric difference as Boolean-ring addition
                    assert_eq!(a.sym_diff(b), a.union(b).inter(&a.inter(b).neg()));
                    assert_eq!(a.sym_diff(a), SubsetU::empty(n));
                    // order
                    assert_eq!(a.inter(b).subset_of(a), true);
                    assert_eq!(a.subset_of(&a.union(b)), true);
                }
            }
        }
    }

    #[test]
    fn test_subset_is_distributive_where_partitions_are_not() {
        // The one contrast the two tiers have at the level of plain lattice identities.
        for n in 0..4 {
            for a in &all_subsets(n) {
                for b in &all_subsets(n) {
                    for c in &all_subsets(n) {
                        assert_eq!(
                            a.inter(&b.union(c)),
                            a.inter(b).union(&a.inter(c)),
                            "Sub(U) must be distributive"
                        );
                    }
                }
            }
        }
    }
}

// ═══════════════════════════════════════════════════════════════════════════
// The three bridges between the tiers
// ═══════════════════════════════════════════════════════════════════════════
//
// `Pi(U)` and `Sub(U)` do not contain one another as lattices — `Pi(U)` is non-distributive
// for `|U| >= 3`, and a sublattice of a distributive lattice is distributive — so the only
// connections are maps. There are three, and each buys one operation and loses the other.

use crate::Partition;
use alloc::vec::Vec as AllocVec;

/// Index a pair `(i, j)` of an `n`-element universe into a subset of `U x U`.
#[inline]
fn pair_index(n: usize, i: usize, j: usize) -> usize {
    i * n + j
}

/// `dit(pi)` — the set of ordered pairs the partition tells apart, as a subset of `U x U`.
///
/// ⚠ **Built by direct pair enumeration, on purpose.** It would be shorter to derive this from
/// the lattice operations, but then `dit(Meet(a,b)) = dit(a) union dit(b)` would hold because
/// the two sides share code, and a check of it would be a tautology wearing the clothes of a
/// measurement. Reading block ids and comparing them is an *independent* route to the same
/// object, so agreement between the two is evidence rather than bookkeeping.
pub fn dit(p: &Partition) -> SubsetU {
    let ids = p.get_ids();
    let n = ids.len();
    let mut out = SubsetU::empty(n * n);
    for i in 0..n {
        for j in 0..n {
            if ids[i] != ids[j] {
                out.insert(pair_index(n, i, j));
            }
        }
    }
    out
}

/// `indit(pi)` — the equivalence relation, i.e. the complement of `dit` in `U x U`.
pub fn indit(p: &Partition) -> SubsetU {
    dit(p).neg()
}

/// `int(R)` — the largest ditset contained in a relation `R` on an `n`-element universe.
///
/// The right adjoint to the inclusion `Dit(U) -> Sub(U x U)`, and what has to be reintroduced
/// if partitions are to be carried as subsets: the image of `dit` is closed under union but
/// not under intersection, so a meet has to be recovered as `int` of the intersection.
///
/// `dit(pi) subset R` iff `complement(R) subset indit(pi)`, and the smallest equivalence
/// relation containing `complement(R)` is its transitive closure — so `int(R)` is the
/// partition whose blocks are the connected components of `complement(R)`.
///
/// Those components are a **Join fold over edge partitions**, not a hand-written union-find:
/// the components *are* the transitive closure, and Join *is* that closure. Keeping it a
/// lattice operation is the point.
pub fn int_(r: &SubsetU, n: usize) -> Partition {
    let mut acc = Partition::from_ids((0..n as u32).collect::<AllocVec<u32>>());
    for i in 0..n {
        for j in 0..n {
            if i == j || r.contains(pair_index(n, i, j)) {
                continue;
            }
            let mut edge: AllocVec<u32> = (0..n as u32).collect();
            let (lo, hi) = if i < j { (i, j) } else { (j, i) };
            edge[hi] = edge[lo];
            acc = acc.integrate(&Partition::from_ids(edge));
        }
    }
    acc
}

/// The cross `K(S) = {S, complement(S)}`, with the empty block dropped.
///
/// Spencer-Brown's cross, as a map from the indication tier to the distinction tier. It is
/// two-to-one — `K(S) = K(complement(S))` — and that is precisely the one bit the distinction
/// tier cannot see: which side was *marked*.
pub fn cross(s: &SubsetU) -> Partition {
    let n = s.size();
    let ids: AllocVec<u32> = (0..n).map(|i| u32::from(s.contains(i))).collect();
    Partition::from_ids(ids)
}

/// Every two-block partition, plus the blob — the image of the cross.
///
/// Order `2^(n-1)` for `n >= 1`, since `K` identifies each subset with its complement.
pub fn cross_image(n: usize) -> AllocVec<Partition> {
    let mut out: AllocVec<Partition> = all_subsets(n).iter().map(cross).collect();
    out.sort_by_key(|p| p.get_ids().to_vec());
    out.dedup_by_key(|p| p.get_ids().to_vec());
    out
}

#[cfg(test)]
mod bridge_tests {
    use super::*;

    /// Test-local enumeration of `Pi(n)`.
    ///
    /// `pcc_arms::all_partitions` would do, but it sits behind the non-default `research`
    /// feature, and a test that only runs under a feature nobody enables is a test that does
    /// not run. Restricted growth strings, six lines.
    fn all_parts(n: usize) -> AllocVec<Partition> {
        let mut ids = alloc::vec![0u32; n];
        let mut out: AllocVec<Partition> = AllocVec::new();
        fn rec(i: usize, n: usize, max: u32, ids: &mut [u32], out: &mut AllocVec<Partition>) {
            if i == n {
                out.push(Partition::from_ids(ids.to_vec()));
                return;
            }
            for b in 0..=max + 1 {
                ids[i] = b;
                rec(i + 1, n, max.max(b), ids, out);
            }
        }
        if n == 0 {
            return out;
        }
        rec(1, n, 0, &mut ids, &mut out);
        out
    }

    #[test]
    fn test_bridge_dit_is_independent_of_the_lattice_ops() {
        // The pre-registered control: `dit` must not be computed *through* Meet, or the
        // identity below would be bookkeeping. Here the two routes are separate, and the
        // cardinality route (`incidence::dit_count`, long predating this module) agrees.
        for n in 1..=5 {
            for p in all_parts(n) {
                assert_eq!(
                    dit(&p).card() as i64,
                    crate::incidence::dit_count(&p),
                    "pair enumeration must agree with the cardinality route"
                );
            }
        }
    }

    #[test]
    fn test_bridge_dit_carries_meet_to_union_and_loses_join() {
        // L-VM orientation: Meet is the common refinement, so Meet is what `dit` buys.
        let mut join_exact = 0;
        let mut join_total = 0;
        for n in 2..=4 {
            let ps = all_parts(n);
            for a in &ps {
                for b in &ps {
                    assert_eq!(
                        dit(&a.differentiate(b)),
                        dit(a).union(&dit(b)),
                        "dit must carry Meet to union exactly"
                    );
                    join_total += 1;
                    if dit(&a.integrate(b)) == dit(a).inter(&dit(b)) {
                        join_exact += 1;
                    }
                }
            }
        }
        assert!(
            join_exact < join_total,
            "dit must LOSE Join — if it carried it too, one embedding would buy both"
        );
    }

    #[test]
    fn test_bridge_int_recovers_the_join_that_dit_loses() {
        for n in 2..=4 {
            let ps = all_parts(n);
            for a in &ps {
                for b in &ps {
                    assert_eq!(
                        int_(&dit(a).inter(&dit(b)), n).get_ids(),
                        a.integrate(b).get_ids(),
                        "int(dit(a) inter dit(b)) must be the Join"
                    );
                }
            }
        }
    }

    #[test]
    fn test_bridge_int_is_a_coreflection() {
        for n in 1..=5 {
            for p in all_parts(n) {
                assert_eq!(int_(&dit(&p), n).get_ids(), p.get_ids());
            }
        }
    }

    #[test]
    fn test_bridge_cross_folds_two_to_one_and_that_is_the_mark() {
        for n in 1..=6 {
            for s in all_subsets(n) {
                assert_eq!(
                    cross(&s).get_ids(),
                    cross(&s.neg()).get_ids(),
                    "K(S) = K(complement S) — the marked side is exactly what is lost"
                );
            }
            assert_eq!(cross_image(n).len(), 1usize << (n - 1));
        }
    }

    #[test]
    fn test_bridge_cross_kernel_is_empty_and_full() {
        for n in 1..=6 {
            let blob = Partition::from_ids(alloc::vec![0u32; n]);
            let kernel: AllocVec<AllocVec<usize>> = all_subsets(n)
                .iter()
                .filter(|s| cross(s).get_ids() == blob.get_ids())
                .map(|s| s.to_indices())
                .collect();
            assert_eq!(kernel.len(), 2, "kernel must be exactly two elements at n={n}");
            assert!(kernel.contains(&AllocVec::new()));
            assert!(kernel.contains(&(0..n).collect::<AllocVec<usize>>()));
        }
    }

    #[test]
    fn test_bridge_cross_is_not_monotone() {
        let n = 3;
        let s = SubsetU::from_indices(n, &[0]);
        let t = SubsetU::from_indices(n, &[0, 1]);
        assert!(s.subset_of(&t));
        let (ks, kt) = (cross(&s), cross(&t));
        assert!(
            !ks.refines(&kt) && !kt.refines(&ks),
            "K must send some inclusion to an incomparable pair"
        );
    }
}
